func loadExpenses() ([]Expense, error) {
	data, err := os.ReadFile("expense.json")
	if err != nil {
		if os.IsNotExist(err) {
			return []Expense{}, nil
		}
		return nil, err
	}

	var expense []Expense
	err = json.Unmarshal(data, &expense)
	if err != nil {
		return nil, err
	}
	return expense, err
}

func saveExpenses(expenses []Expense) error {
	savedData, err := json.MarshalIndent(expenses, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile("expense.json", savedData, 0664)
}
